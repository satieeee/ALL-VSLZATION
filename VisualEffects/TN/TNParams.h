static TNMat g_tnMetalB= { {0.30f, 0.38f, 0.52f, 1.0f} };
static TNMat g_tnPaperA= { {0.88f, 0.90f, 0.95f, 1.0f} };
static TNMat g_tnPaperB= { {0.34f, 0.30f, 0.44f, 1.0f} };
