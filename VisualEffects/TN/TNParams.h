const  float TN_BASE_SPD = 2.2f;    // 基础推进速度（世界单位/秒）
const  float TN_HIT_RATE = 14.0f;   // 鼓点时的速度倍率上界
// 中轴纽结的辉光强度：常驻底值 + 鼓点冲击。这两个数就是"极度夸张"的总闸 ——
// 场景 FBO 是 RGBA16F，这里给多少，泛光那几趟就炸多大。
const  float TN_KNOT_GLOW_BASE = 7.0f;    // 常驻（已经明显过曝）
const  float TN_KNOT_GLOW_HIT  = 17.0f;   // 鼓点那一刻再顶上去，合计 ~24
// 隧道壁棱脊的炫彩辉光：同一套思路。常驻给 5（棱是细线，比纽结那种实心管要弱一点
// 才不至于把整个画面糊白），鼓点冲到 ~25。
const  float TN_EDGE_GLOW_BASE = 5.0f;
const  float TN_EDGE_GLOW_HIT  = 20.0f;
// 【浅色模式必须另给一组小值】—— 合成那一趟最后有一句
//     if (uDarkBg == 0) col = vec3(1.0) - col;
// 整幅反相，而反相作用在【已经被 ACES 压到 [0,1] 的颜色】上。所以深色模式下那套
// HDR 玩法在浅色模式下会反过来：推到 25 的棱脊被压成纯白 1.0，反相之后是纯黑 0.0 ——
// "辉光"正好变成"黑洞"，用户看到的就是"没看见任何光"。
// 浅色模式给一个小值，让棱脊停在中间亮度：反相后是一条深色的边，仍然是画面最亮眼的结构。
// 【数值要贴到 1.0 附近】反相后想要"一条深色的边"，反相【前】就得接近 1.0
// （墙面本身约 0.3，所以棱脊那项给 0.55 左右，加起来 0.85 → 反相后 0.15，一条深色的边）。
// 鼓点顶到 >1 会被 ACES 裁成纯白 → 反相后纯黑 —— 正好是"更重"的那一下。
const  float TN_EDGE_GLOW_LIGHT_BASE = 0.55f;
const  float TN_EDGE_GLOW_LIGHT_HIT  = 0.50f;

// ---- 金属细条的【边】辉光（2026-09-24 起，辉光的落点就是这里）----
// 背景：隧道壁在 2026-09-23 被删掉之后，上面那套"壁棱脊"辉光就再没有一次绘制会走到 ——
// 泛光照不出东西，实机看起来"不显示辉光"。用户要的是"给已有的边加辉光"，
// 而现在画面里【已有的边】就是金属细条的两条长边（细条本来就是隧道的纵向脊）。
const  float TN_RIB_GLOW_BASE = 6.0f;    // 深色：常驻（远超 1，泛光从这里炸开）
const  float TN_RIB_GLOW_HIT  = 20.0f;   // 鼓点那一刻顶到 ~26
// 【浅色模式：要的不是"调小一点"，而是"峰值贴 1、通道差拉大"】
// 合成最后一句是 `if (uDarkBg == 0) col = vec3(1.0) - col;`，作用在【ACES 压过的 [0,1]】上。
// 于是：
//   · 三通道一起顶到 1 → 反相是纯黑 —— 那正是"黑洞"，用户看到的就是"没看见任何光"
//   · 一个通道顶到 1、另两个明显低 → 反相是 (0, 0.6, …) 的饱满彩边，这才是浅色模式要的"炫彩"
// 【但强度反而要比直觉大】实测：3.0 才够，0.55（壁那套浅色值）几乎无色、1.3 是脏橄榄色。
// 原因有两条，缺一条都会把峰压下去：① 几何趟最后还有一句 `col *= vFog`，远端细条先被压暗一遍；
// ② ACES 是按亮度整体缩放的（`col *= lumT/lum0`），峰值越高缩放越狠，不是"给多少就是多少"。
// 好消息：本设计的色相 rc = tvHue(h) + 0.35*tvHue(h+0.5) 最小通道 ≈ 0.35×最大通道，
// 单根条**永远出不了黑洞**；只有多根异色条重叠才可能糊成灰（灰不是黑，仍可接受）。
const  float TN_RIB_GLOW_LIGHT_BASE = 3.00f;
const  float TN_RIB_GLOW_LIGHT_HIT  = 0.90f;
// 辉光带在 vUV.x 上的半宽。细条的 u 横跨【整条宽】（VTRibbonBuild 里 qu 写在 +S/-S 两侧），
// 所以 0.30 = 每条长边各占 30% 宽度。
// 【为什么是 0.30 而不是 0.16】—— 浅色模式下"有颜色的边"必须够宽才读得出来：
// 0.16 时彩边只有发丝那么细，浅色图几乎看不到颜色；0.30 才成一条彩边。
// 代价是深色模式里箔面被吃掉大半（整根偏发光、"金属条"的质感变弱），要回收就调小这个数。
const  float TN_RIB_GLOW_W = 0.30f;

// ---- 音乐频谱贴在细条的两条长边上（2026-09-24）----
// 16 个频段（AudioFrame.fft，对数频段、攻击平滑）沿【条长】摊开：v=0 是低频、v=1 是高频，
// 段间线性插值免得台阶太硬。每根条再加一个由 vPhase 来的偏移，免得所有针像同一张条形图。
// 亮度 = 该频段响度；颜色 = 随机（每根条 × 每频段 × 每下鼓点 一个色）。
//
// 【两套强度，理由同 TN_RIB_GLOW_LIGHT_*】浅色模式最后是 `1 - col`，峰值顶到 1 就变纯黑。
// 深色这套直接进 HDR（泛光跟着频谱一起炸），浅色这套贴在 1 附近（反相后是有颜色的边）。
// 【基准 = 原来的样子】—— 没有音乐的时候，画面必须跟"加频谱之前"一模一样：
//   静止 → 亮度 = 原辉光、边宽 = 原带宽、颜色 = 彩虹、针长 = 原长。
// 频谱只负责【往上加】。所以下面每一个"倍率"的静止端都是 1.0。
//
// 【为什么必须是 1.0 起步】第一版把静止端给成 0.05（想"安静就暗下去"），结果没音乐时
// 整幅是灰白的 —— 那已经不是"原来的图形"了，而是"整体调暗"。用户指出"基准不是 0，
// 是原来基本的图形"，这一版就是按这条改的。
//
// 亮度 = 原辉光 × mix(GAIN_BASE, GAIN_MAX, 该频段响度)
// 深色：最响 = 6×2.4 ≈ 14（远超 1，泛光跟着炸）
// 浅色：最响 = 3×1.75 ≈ 5（过曝 → 反相成深色边，两端差距最大）
const  float TN_SPEC_GAIN_BASE  = 1.00f;   // 静止（= 原样，不许改）
const  float TN_SPEC_GAIN_DARK  = 2.40f;   // 深色：最响
const  float TN_SPEC_GAIN_LIGHT = 1.75f;   // 浅色：最响
// 边宽：静止 = 原带宽（1.0），最响 = 再宽 1+AMT 倍。
const  float TN_RIB_WIDE_AMT    = 1.60f;
// 安静频段的倍率。给 0 的话安静段落整根针是黑的（边上什么都没有）；0.05 = 几乎全暗。
// 频谱沿条长摊开的频段数等见下。
// 沿条长摊开的频段数。【必须等于 kAudioBands】（AudioAnalyzer.h），否则越界读到 0。
// 台子与实机都从这一份取，所以改这里就够了。
const  int    TN_SPEC_BANDS    = 16;
// 针的【长短】：BASE = 静止时的倍率，MAX = 最响时的倍率。
// 【BASE 必须是 1.0】—— 1.0 就是【原来的图形本身】，这是基准：没有音乐的时候
// 画面要跟原来一模一样，频谱只负责【往上加】，不该把安静的针缩得比原图短。
// （第一版给了 0.30~1.60，静音的针缩成一小截 —— 那不是"基准"，是"整体缩短"。）
// 缩放的锚点在【针的远端】：响的频段那几根针朝镜头方向伸出来。
// 给每个顶点带一个"原本多长"才能这么算，见 VTGeom.h 的 VTRibbonStride。
const  float TN_RIB_LEN_BASE   = 1.00f;   // 静止 = 原始图形
const  float TN_RIB_LEN_MAX    = 1.85f;   // 最响 = 比原始长 85%

// 鼓点那一刻相机沿视轴【猛推一下】的幅度（世界单位，正数 = 往隧道里推）。
// 触发信号就是同一套 hitdetect：命中瞬间 gs=1（推动量立刻到位 → "瞬间"），
// 之后按 TN_HIT_DUR / TN_HIT_CURVE 弹回来。和手持镜头的抖共用同一个包络，
// 所以它俩是"同一下鼓点、一起动"，不会各弹各的。
// 【别调太大】相机往 +z 走 = 几何的视深变小，靠得极近的那些会被 d=max(p.z,0.05)
// 放大成很大的三角形 —— 挡住它们的是近端淡出（fadeNear 在 z<1.5 时为 0），
// 所以只有在推进量超过 ~1.5 时才会看见"糊过来"的边角。
// ---- 细条的【形状参数】----
// 【基准 = 原样】：没有过渡/没有驱动的时候，画面必须跟"加这套之前"逐像素一致。
// 所以基准值全是恒等（宽度 1 / 径向 1 / 缠绕 0）。
// 【退场值】：切换走的时候朝这组值插值（细条一边拧一边收拢、变细，然后淡出）。
// 台子有参数扫描可看每个值的形态（_hittest 里渲一排）。
const  float TN_RIB_WIDTH_BASE   = 1.00f;
const  float TN_RIB_SPREAD_BASE  = 1.00f;
const  float TN_RIB_CURL_BASE    = 0.00f;
const  float TN_RIB_WIDTH_EXIT   = 0.25f;   // 收场时截面缩到 1/4
const  float TN_RIB_SPREAD_EXIT  = 0.30f;   // 向隧道轴收拢
const  float TN_RIB_CURL_EXIT    = 0.32f;   // 每单位 z 转 0.32 弧度 → 30 个单位转 9.6 弧度 ≈ 1.5 圈

const  float TN_HIT_PUSH = 1.10f;

