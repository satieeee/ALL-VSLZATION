// 【第一版给太暗了】原来 (0.055,0.085,0.135) 与背景中心 (0.035,0.042,0.082) 只差 1.6×，
// 过完 ACES 之后两者都在 15/255 上下，画面等于一片黑（离线台实测峰值 14，白查一轮）。
