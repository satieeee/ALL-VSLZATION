// 每根细条的横向摆动幅度见 VTGeom.h 的 VT_RIB_WAVE（离线台也要用同一份）。
// 细条不沿 z 动 —— 隧道壁在动，它们相对地"掠过去"就是流动感；
// 让它们自己也沿 z 滑会和层次的环绕打架。

// 调色与光
// 棱脊辉光的带宽（占最大半径的比例）。【要窄】：这个数一宽，棱脊旁边大半面墙都会被
// 点着，彩虹就摊成一整片而不是"一条边"。0.16 那版实测就是整面墙在发光。
// 断面半径在 1.408~1.827 之间，棱峰(r≈1.83) 的 outerness≈0.015、谷底(r≈1.41)≈0.23，
// 所以 0.05 只点亮最靠近棱脊的那一条带。
const float TN_RIM_W = 0.05f;
const float TN_RIM_I = 1.05f;
const float TN_PAPER_INSET_MIN = 0.28f;   // 剪纸内缩量（占格子特征尺寸的比例）

